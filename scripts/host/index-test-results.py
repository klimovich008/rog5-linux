#!/usr/bin/env python3
"""Write test-results/README.md: every dated report grouped by month, with its first heading.

Existing reports are never changed; only the index is generated.

    python3 scripts/host/index-test-results.py           # rewrite the index
    python3 scripts/host/index-test-results.py --check   # fail if it is stale
"""
import argparse
import collections
from pathlib import Path
import re
import subprocess
import sys

REPO = Path(__file__).resolve().parents[2]
RESULTS = REPO / 'test-results'
INDEX = RESULTS / 'README.md'
DATED = re.compile(r'^(\d{4})-(\d{2})-\d{2}-')
MONTHS = ('January', 'February', 'March', 'April', 'May', 'June', 'July', 'August',
          'September', 'October', 'November', 'December')


def title(path):
    try:
        for line in path.read_text(errors='replace').splitlines()[:40]:
            if line.startswith('#'):
                return line.lstrip('#').strip().replace('|', '/')
    except OSError:
        pass
    return ''


def entries(repo):
    listed = subprocess.run(['git', '-C', str(repo), 'ls-files', '-z', '--', 'test-results'],
                            capture_output=True, check=True).stdout.decode().split('\0')
    names = sorted({Path(p).relative_to('test-results').parts[0] for p in listed if p})
    months = collections.OrderedDict()
    for name in names:
        match = DATED.match(name)
        if not match:
            continue
        months.setdefault(match.group(1, 2), []).append(name)
    return months


def render(repo=REPO):
    months = entries(repo)
    results = repo / 'test-results'
    lines = ['# Test results index', '',
             'Generated by `scripts/host/index-test-results.py`; do not edit by hand. Reports are',
             'dated records and are never rewritten. Newest month first; within a month in date',
             'order. Subdirectories hold multi-file results.', '']
    for (year, month), names in sorted(months.items(), reverse=True):
        lines.append(f'## {MONTHS[int(month) - 1]} {year} ({len(names)})')
        lines.append('')
        for name in names:
            path = results / name
            if path.is_dir():
                lines.append(f'- [{name}/]({name}/)')
            elif name.endswith('.md'):
                heading = title(path)
                lines.append(f'- [{name}]({name})' + (f': {heading}' if heading else ''))
            else:
                lines.append(f'- [{name}]({name})')
        lines.append('')
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if not INDEX.is_file() or INDEX.read_text() != text:
            print('FAIL test-results/README.md is stale: run scripts/host/index-test-results.py', file=sys.stderr)
            return 1
        print('PASS test-results/README.md indexes every dated result')
        return 0
    INDEX.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
